import AppKit
import ClipsuCore

/// Reads new pasteboard contents, applies privacy + dedup rules, persists them,
/// and kicks off OCR for images. Heavy work runs off the main thread.
final class CaptureService {
    private let database: Database
    private let imageStore: ImageStore
    private let ocr: OCRService
    private let settings: AppSettings
    private let work = DispatchQueue(label: "ai.clipsu.capture", qos: .utility)

    /// Invoked on the main thread after the store changes, so the UI can refresh.
    var onStoreChanged: (() -> Void)?

    // Markers set by password managers and transient producers; never store these.
    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    init(database: Database, imageStore: ImageStore, ocr: OCRService, settings: AppSettings) {
        self.database = database
        self.imageStore = imageStore
        self.ocr = ocr
        self.settings = settings
    }

    /// Lightweight snapshot read from the pasteboard on the main thread.
    private struct Payload {
        var kind: ClipKind
        var plainText: String?
        var richData: Data?
        var imageData: Data?
        var fileURLs: [String]?
        var hashSource: Data
    }

    /// Called on the main thread by the monitor.
    func capture(from pasteboard: NSPasteboard) {
        guard !settings.paused else { return }

        // Privacy: skip concealed/transient pasteboards (passwords, one-time content).
        if settings.ignoreConcealed {
            let types = pasteboard.types ?? []
            if types.contains(Self.concealedType) || types.contains(Self.transientType) || types.contains(Self.autoGeneratedType) {
                return
            }
        }

        // Source application (the app that was frontmost when the copy happened).
        let frontApp = NSWorkspace.shared.frontmostApplication
        let sourceBundleID = frontApp?.bundleIdentifier
        let sourceAppName = frontApp?.localizedName

        if let bid = sourceBundleID, settings.excludedBundleIDs.contains(bid) { return }

        guard let payload = readPayload(from: pasteboard) else { return }

        let byteSize = payload.hashSource.count
        if byteSize > settings.maxItemBytes { return }

        work.async { [weak self] in
            self?.persist(payload, sourceBundleID: sourceBundleID, sourceAppName: sourceAppName, byteSize: byteSize)
        }
    }

    // MARK: - Reading

    private func readPayload(from pb: NSPasteboard) -> Payload? {
        // 1. File copies.
        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map { $0.path }
            let preview = paths.map { ($0 as NSString).lastPathComponent }.joined(separator: ", ")
            return Payload(kind: .file, plainText: preview, richData: nil, imageData: nil,
                           fileURLs: paths, hashSource: Data(paths.joined(separator: "\n").utf8))
        }

        // 2. Image content (prefer PNG, fall back to TIFF).
        if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff) {
            return Payload(kind: .image, plainText: nil, richData: nil, imageData: data,
                           fileURLs: nil, hashSource: data)
        }

        // 3. Rich text (keep RTF for formatted paste, plus a plain preview).
        if let rtf = pb.data(forType: .rtf) {
            let plain = pb.string(forType: .string)
                ?? NSAttributedString(rtf: rtf, documentAttributes: nil)?.string
            let text = plain ?? ""
            return Payload(kind: .richText, plainText: text, richData: rtf, imageData: nil,
                           fileURLs: nil, hashSource: Data(text.utf8))
        }

        // 4. Plain string → classify as text / link / color.
        if let string = pb.string(forType: .string), !string.isEmpty {
            let kind = ContentClassifier.kind(forPlainText: string)
            return Payload(kind: kind, plainText: string, richData: nil, imageData: nil,
                           fileURLs: nil, hashSource: Data(string.utf8))
        }

        return nil
    }

    // MARK: - Persistence (background)

    private func persist(_ payload: Payload, sourceBundleID: String?, sourceAppName: String?, byteSize: Int) {
        let hash = Hashing.sha256(payload.hashSource)

        // Dedup.
        do {
            let existing: ClipboardItem?
            switch settings.dedupScope {
            case .lastOnly: existing = try database.mostRecent().flatMap { $0.contentHash == hash ? $0 : nil }
            case .all:      existing = try database.findByHash(hash)
            }
            if let existing {
                try database.bumpUsage(id: existing.id)
                notifyChanged()
                return
            }
        } catch {
            Log.error("dedup check failed: \(error)")
        }

        // Build the item (saving image to disk if needed).
        var imagePath: String?
        var thumbPath: String?
        var width: Int?
        var height: Int?
        var effectiveSize = byteSize

        if payload.kind == .image, let data = payload.imageData {
            do {
                let saved = try imageStore.save(imageData: data)
                imagePath = saved.imagePath
                thumbPath = saved.thumbPath
                width = saved.width
                height = saved.height
                effectiveSize = saved.byteSize
            } catch {
                Log.error("image save failed: \(error)")
                return
            }
        }

        let item = ClipboardItem(
            kind: payload.kind,
            plainText: payload.plainText,
            richData: payload.richData,
            ocrText: nil,
            imagePath: imagePath,
            thumbPath: thumbPath,
            imageWidth: width,
            imageHeight: height,
            fileURLs: payload.fileURLs,
            sourceBundleID: sourceBundleID,
            sourceAppName: sourceAppName,
            contentHash: hash,
            byteSize: effectiveSize
        )

        do {
            let inserted = try database.insert(item)
            notifyChanged()

            // OCR images so they become searchable.
            if payload.kind == .image, let data = payload.imageData,
               settings.ocrEnabled, effectiveSize <= settings.ocrSkipBytes {
                ocr.recognizeText(in: data) { [weak self] text in
                    guard let self, let text, !text.isEmpty else { return }
                    try? self.database.updateOCR(id: inserted.id, text: text)
                    self.notifyChanged()
                }
            }
        } catch {
            Log.error("insert failed: \(error)")
        }
    }

    private func notifyChanged() {
        DispatchQueue.main.async { [weak self] in self?.onStoreChanged?() }
    }
}
